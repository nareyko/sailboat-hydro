#!/usr/bin/env python3
"""Generate MkDocs model + formula pages from bundled nordic_benchmark.json.

  python scripts/generate_docs_models.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "src" / "sailboat_hydro" / "data" / "nordic_benchmark.json"
DOCS = ROOT / "docs"


def main() -> None:
    payload = json.loads(DATA.read_text(encoding="utf-8"))
    models = sorted(
        payload["models"],
        key=lambda m: (m["brand_slug"], m["model_slug"]),
    )
    if len(models) != 93:
        raise SystemExit(f"expected 93 models, got {len(models)}")

    lines = [
        "<!-- GENERATED by scripts/generate_docs_models.py — do not hand-edit -->",
        "",
        "# 93-model index",
        "",
        "Canonical cards on [fairhelm.com](https://fairhelm.com/en/yachts/models/).",
        f"Benchmark DOI: [{payload['zenodo_doi']}]({payload['zenodo_doi']}).",
        "",
        "| # | Model | Brand / slug | LOA (m) | Card |",
        "|---|---|---|---|---|",
    ]
    for i, m in enumerate(models, 1):
        url = m["links"]["canonical_model_url"]
        loa = m.get("loa_m")
        loa_s = f"{loa:.2f}" if isinstance(loa, (int, float)) else "—"
        slug = f"{m['brand_slug']}/{m['model_slug']}"
        lines.append(f"| {i} | {m['name']} | `{slug}` | {loa_s} | [{slug}]({url}) |")
    lines.append("")
    DOCS.mkdir(exist_ok=True)
    (DOCS / "models.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    f_lines = [
        "<!-- GENERATED by scripts/generate_docs_models.py — do not hand-edit -->",
        "",
        "# Formulas",
        "",
        (
            "Methodology hub: "
            f"[{payload['formulas_methodology_url']}]({payload['formulas_methodology_url']})"
        ),
        "",
        "| Formula | URL |",
        "|---|---|",
    ]
    for formula in payload.get("formulas", []):
        f_lines.append(
            f"| {formula['title']} | [{formula['slug']}]({formula['url']}) |"
        )
    f_lines.append("")
    (DOCS / "formulas.md").write_text("\n".join(f_lines) + "\n", encoding="utf-8")
    print(f"OK: docs/models.md ({len(models)}) · docs/formulas.md ({len(payload.get('formulas', []))})")


if __name__ == "__main__":
    main()
